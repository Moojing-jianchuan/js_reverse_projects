const fs = require('fs');
const zlib = require('zlib');
const b64 = fs.readFileSync('config/sample_deflate.b64', 'utf8').trim();
const j = zlib.inflateSync(Buffer.from(b64, 'base64')).toString('utf8');
const obj = JSON.parse(j.slice(32));
console.log('TrackStartTime:', obj.TrackStartTime);
console.log('VerifyTime:', obj.VerifyTime);
console.log('xPos:', JSON.stringify(obj.xPos));
console.log('slidePos:', JSON.stringify(obj.slidePos));
console.log('arg:', JSON.stringify(obj.arg));
const tl = obj.TrackList;
const pts = tl.mp.split('|').map(s => s.split(',').map(Number));
const mcs = tl.mc.split(',').map(Number);
console.log('mp first/last:', pts[0], pts[pts.length - 1], 'deltaX', pts[pts.length - 1][0] - pts[0][0]);
console.log('mc x,y:', mcs[0], mcs[1]);
console.log('mu:', tl.mu);
const mms = tl.mm.split('|').map(s => s.split(',').map(Number));
console.log('mm last 3:', mms.slice(-3));
console.log('deltaX total (mu - mc):', Number(tl.mu.split(',')[0]) - mcs[0]);
